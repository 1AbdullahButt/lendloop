// @vitest-environment node
// AC18: exported n8n workflows and every tracked (or about-to-be-committed) file are free of secrets.
// Runs in Node because it needs the filesystem and `git ls-files`.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, test } from "vitest";

const ROOT = process.cwd();
const WORKFLOW_DIR = join(ROOT, "n8n", "workflows");
const WORKFLOWS = ["request-notification.json", "overdue-reminders.json", "error-handler.json"] as const;

// Patterns are token-shaped (prefix + a run of key characters) so prose that merely
// names a prefix, such as this suite's own docs, does not match.
const SECRET_PATTERNS: Array<[string, RegExp]> = [
  ["Stripe/Clerk-style secret key (sk_)", /\bsk_(live|test)_[A-Za-z0-9]{10,}/],
  ["live publishable key (pk_live)", /\bpk_live_[A-Za-z0-9]{10,}/],
  ["Clerk publishable key (pk_test)", /\bpk_test_[A-Za-z0-9]{10,}/],
  ["webhook signing secret (whsec_)", /\bwhsec_[A-Za-z0-9+/=]{10,}/],
  ["PEM block (-----BEGIN)", /-----BEGIN [A-Z ]+-----/],
  ["Slack webhook URL", /hooks\.slack\.com\/services\/[A-Za-z0-9/]+/],
  ["Discord webhook URL", /discord(app)?\.com\/api\/webhooks\/\d+\/[\w-]+/],
  ["URL with credential query param", /https?:\/\/[^\s"'`]*[?&](token|key|secret|signature|sig|apikey|api_key|access_token)=[^&\s"'`]+/i],
];

const EMAIL = /[A-Za-z0-9._%+-]+@([A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,})/g;
function isAllowedEmailDomain(domain: string): boolean {
  const d = domain.toLowerCase();
  return d === "example.com" || d.endsWith(".example.com");
}

// Exclusions, each justified:
// - package-lock.json: generated by npm; registry URLs and integrity hashes, not our content.
// - binary assets: not text, cannot hold a pasted secret in a reviewable way.
const EXCLUDED_FILES = new Set(["package-lock.json"]);
const BINARY_EXT = /\.(ico|png|jpe?g|gif|webp|woff2?|ttf|otf|pdf|zip|gz)$/i;
// - KICKOFF.md (email check only): the course brief's own submission address. It is
//   instructions to the human, never processed by LendLoop. Secret patterns still apply.
const EMAIL_EXCLUDED_FILES = new Set(["KICKOFF.md"]);

function repoFiles(): string[] {
  // Tracked files plus untracked-but-not-ignored ones: anything that could be committed next.
  const out = execFileSync("git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard"], {
    cwd: ROOT,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  return out
    .split("\0")
    .filter(Boolean)
    .filter((f) => existsSync(join(ROOT, f)))
    .filter((f) => !EXCLUDED_FILES.has(f) && !BINARY_EXT.test(f));
}

function readText(rel: string): string | null {
  const buf = readFileSync(join(ROOT, rel));
  if (buf.subarray(0, 8000).includes(0)) return null; // binary
  return buf.toString("utf8");
}

function envNamesFromExample(): string[] {
  const text = readFileSync(join(ROOT, ".env.example"), "utf8");
  const names = new Set<string>();
  for (const line of text.split(/\r?\n/)) {
    const m = /^\s*#?\s*([A-Z][A-Z0-9_]*)=/.exec(line);
    if (m) names.add(m[1]);
  }
  return [...names];
}

function parseDotenv(path: string): Record<string, string> {
  if (!existsSync(path)) return {};
  const out: Record<string, string> = {};
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const m = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/.exec(line);
    if (!m) continue;
    out[m[1]] = m[2].replace(/^(['"])(.*)\1$/, "$2").trim();
  }
  return out;
}

/** Values of the .env.example names from process.env and the git-ignored local env files. */
function sensitiveValues(): Array<{ name: string; value: string }> {
  const names = envNamesFromExample();
  const sources = [
    process.env as Record<string, string | undefined>,
    parseDotenv(join(ROOT, ".env.local")),
    parseDotenv(join(ROOT, ".env")),
    parseDotenv(join(ROOT, "n8n", ".env")),
  ];
  const found: Array<{ name: string; value: string }> = [];
  for (const name of names) {
    for (const src of sources) {
      const raw = src[name];
      if (!raw) continue;
      // ADMIN_EMAILS is a list; check each address on its own.
      for (const value of raw.split(",").map((v) => v.trim())) {
        if (value.length >= 8) found.push({ name, value });
      }
    }
  }
  return found;
}

function loadWorkflow(name: string): { raw: string; json: { nodes?: N8nNode[]; [k: string]: unknown } } {
  const raw = readFileSync(join(WORKFLOW_DIR, name), "utf8");
  return { raw, json: JSON.parse(raw) };
}

type N8nNode = {
  name: string;
  type: string;
  parameters?: Record<string, unknown>;
  credentials?: Record<string, unknown>;
  retryOnFail?: boolean;
  maxTries?: number;
  waitBetweenTries?: number;
};

function codeOf(node: N8nNode): string {
  const p = node.parameters ?? {};
  return String(p.jsCode ?? p.functionCode ?? p.code ?? "");
}

describe("AC18: n8n workflow exports", () => {
  test("AC18: the three workflow exports exist and parse as n8n workflows", () => {
    const missing = WORKFLOWS.filter((f) => !existsSync(join(WORKFLOW_DIR, f)));
    expect(missing, `missing n8n/workflows/${missing.join(", n8n/workflows/")}`).toEqual([]);
    for (const f of WORKFLOWS) {
      const { json } = loadWorkflow(f);
      expect(Array.isArray(json.nodes), `${f} has a nodes array`).toBe(true);
      expect(json.nodes!.length, `${f} has nodes`).toBeGreaterThan(0);
    }
  });

  test("AC18: workflow JSON contains no secret patterns, token URLs or non-example emails", () => {
    for (const f of WORKFLOWS) {
      expect(existsSync(join(WORKFLOW_DIR, f)), `n8n/workflows/${f} is missing`).toBe(true);
      const { raw } = loadWorkflow(f);
      for (const [label, re] of SECRET_PATTERNS) {
        expect(re.test(raw), `${f} contains ${label}`).toBe(false);
      }
      const emails = [...raw.matchAll(EMAIL)].filter((m) => !isAllowedEmailDomain(m[1])).map((m) => m[0]);
      expect(emails, `${f} contains real email addresses`).toEqual([]);
      // Convex deployment URLs come from $env.CONVEX_SITE_URL, never hard-coded.
      expect(/[a-z0-9-]+\.convex\.(site|cloud)/i.test(raw), `${f} hard-codes a Convex deployment URL`).toBe(false);
    }
  });

  test("AC18: credentials are referenced by id/name only, with no inline secret data", () => {
    for (const f of WORKFLOWS) {
      const { json } = loadWorkflow(f);
      for (const node of json.nodes ?? []) {
        for (const [type, ref] of Object.entries(node.credentials ?? {})) {
          expect(typeof ref, `${f} / ${node.name} credential ${type}`).toBe("object");
          const keys = Object.keys(ref as object).sort();
          for (const k of keys) {
            expect(["id", "name"], `${f} / ${node.name} credential ${type} has inline field ${k}`).toContain(k);
          }
        }
      }
      expect(json).not.toHaveProperty("credentials");
    }
  });

  test("AC18: Code nodes read the HMAC secrets from $env (never literal values)", () => {
    const envRef = (name: string) => new RegExp(`\\$env(\\.${name}\\b|\\[\\s*['"]${name}['"]\\s*\\])`);

    const req = loadWorkflow("request-notification.json").json.nodes ?? [];
    const reqCode = req.filter((n) => n.type === "n8n-nodes-base.code").map(codeOf).join("\n");
    expect(reqCode, "request-notification Code node verifies with $env.CONVEX_TO_N8N_SECRET").toMatch(
      envRef("CONVEX_TO_N8N_SECRET"),
    );
    expect(reqCode, "request-notification uses a constant-time compare").toMatch(/timingSafeEqual/);

    const overdue = loadWorkflow("overdue-reminders.json").json.nodes ?? [];
    const overdueCode = overdue.filter((n) => n.type === "n8n-nodes-base.code").map(codeOf).join("\n");
    expect(overdueCode, "overdue-reminders Code node signs with $env.N8N_TO_CONVEX_SECRET").toMatch(
      envRef("N8N_TO_CONVEX_SECRET"),
    );
  });

  test("AC18: the request-notification Webhook node has the raw body option enabled and a 401 response path", () => {
    const nodes = loadWorkflow("request-notification.json").json.nodes ?? [];
    const hooks = nodes.filter((n) => n.type === "n8n-nodes-base.webhook");
    expect(hooks, "exactly one Webhook node").toHaveLength(1);
    const options = (hooks[0].parameters?.options ?? {}) as Record<string, unknown>;
    expect(options.rawBody, "Webhook node options.rawBody").toBe(true);
    const responds = nodes.filter((n) => n.type === "n8n-nodes-base.respondToWebhook");
    const codes = responds.map((n) => (n.parameters?.options as Record<string, unknown> | undefined)?.responseCode);
    expect(codes, "a Respond to Webhook node answers 401 on a bad signature").toContain(401);
  });

  test("AC18 (SPEC 6.3): overdue-reminders has a schedule trigger and HTTP calls to Convex with 3 tries / 10s wait", () => {
    const { raw, json } = loadWorkflow("overdue-reminders.json");
    const nodes = json.nodes ?? [];
    expect(nodes.some((n) => n.type === "n8n-nodes-base.scheduleTrigger"), "schedule trigger").toBe(true);
    expect(raw).toContain("/n8n/overdue-loans");
    expect(raw).toContain("/n8n/reminder-status");
    expect(raw).toMatch(/\$env(\.CONVEX_SITE_URL\b|\[\s*['"]CONVEX_SITE_URL['"]\s*\])/);
    const http = nodes.filter((n) => n.type === "n8n-nodes-base.httpRequest");
    expect(http.length, "HTTP Request nodes").toBeGreaterThanOrEqual(2);
    for (const n of http) {
      expect(n.retryOnFail, `${n.name} retryOnFail`).toBe(true);
      expect(n.maxTries, `${n.name} maxTries`).toBe(3);
      expect(n.waitBetweenTries, `${n.name} waitBetweenTries`).toBe(10000);
    }
  });

  test("AC18 (SPEC 6.3): error-handler starts with an Error Trigger", () => {
    const nodes = loadWorkflow("error-handler.json").json.nodes ?? [];
    expect(nodes.some((n) => n.type === "n8n-nodes-base.errorTrigger")).toBe(true);
  });
});

describe("AC18: repository scan", () => {
  test("AC18: no tracked or committable file contains a secret pattern", () => {
    const hits: string[] = [];
    for (const f of repoFiles()) {
      const text = readText(f);
      if (text === null) continue;
      for (const [label, re] of SECRET_PATTERNS) {
        if (re.test(text)) hits.push(`${f}: ${label}`);
      }
    }
    expect(hits).toEqual([]);
  });

  test("AC18: no tracked or committable file contains an email address outside example.com", () => {
    const hits: string[] = [];
    for (const f of repoFiles()) {
      if (EMAIL_EXCLUDED_FILES.has(f)) continue;
      const text = readText(f);
      if (text === null) continue;
      for (const m of text.matchAll(EMAIL)) {
        // Report the domain only, so the failure output itself does not repeat the address.
        if (!isAllowedEmailDomain(m[1])) hits.push(`${f}: address at ${m[1]}`);
      }
    }
    expect(hits).toEqual([]);
  });

  test("AC18: no tracked or committable file contains the value of any env var named in .env.example", () => {
    const values = sensitiveValues();
    const hits: string[] = [];
    for (const f of repoFiles()) {
      const text = readText(f);
      if (text === null) continue;
      for (const { name, value } of values) {
        // Name and file only: the value must never be printed.
        if (text.includes(value)) hits.push(`${f}: value of ${name}`);
      }
    }
    expect(hits).toEqual([]);
  });

  test("AC18: .env.example lists names only (no values)", () => {
    const text = readFileSync(join(ROOT, ".env.example"), "utf8");
    for (const line of text.split(/\r?\n/)) {
      const m = /^\s*([A-Z][A-Z0-9_]*)=(.*)$/.exec(line);
      if (m) expect(m[2].trim(), `${m[1]} has a value in .env.example`).toBe("");
    }
    expect(envNamesFromExample().length).toBeGreaterThan(0);
  });
});
